import 'package:flutter/material.dart';

/// Translates interface copy; source titles and chapter names fall through.
class LocalizedText extends StatelessWidget {
  const LocalizedText(
    this.data, {
    super.key,
    this.style,
    this.textAlign,
    this.maxLines,
    this.overflow,
    this.softWrap,
    this.textDirection,
    this.semanticsLabel,
    this.textScaler,
    this.textWidthBasis,
    this.textHeightBehavior,
    this.locale,
    this.strutStyle,
    this.selectionColor,
    this.arguments = const {},
  });
  final String data;
  final TextStyle? style;
  final TextAlign? textAlign;
  final int? maxLines;
  final TextOverflow? overflow;
  final bool? softWrap;
  final TextDirection? textDirection;
  final String? semanticsLabel;
  final TextScaler? textScaler;
  final TextWidthBasis? textWidthBasis;
  final TextHeightBehavior? textHeightBehavior;
  final Locale? locale;
  final StrutStyle? strutStyle;
  final Color? selectionColor;
  final Map<String, Object> arguments;
  @override
  Widget build(BuildContext context) => Text(
    translate(data, Localizations.localeOf(context), arguments: arguments),
    style: style,
    textAlign: textAlign,
    maxLines: maxLines,
    overflow: overflow,
    softWrap: softWrap,
    textDirection: textDirection,
    semanticsLabel: semanticsLabel,
    textScaler: textScaler,
    textWidthBasis: textWidthBasis,
    textHeightBehavior: textHeightBehavior,
    locale: locale,
    strutStyle: strutStyle,
    selectionColor: selectionColor,
  );
}

String translate(
  String text,
  Locale locale, {
  Map<String, Object> arguments = const {},
}) {
  final template = locale.languageCode == 'en'
      ? english[text] ?? text
      : locale.countryCode == 'TW'
      ? traditional[text] ?? text
      : text;
  // Replace only explicit UI placeholders in one pass. Source titles and notes
  // are values and must never be translated or parsed as another template.
  return template.replaceAllMapped(
    RegExp(r'\{(\w+)\}'),
    (match) => arguments[match[1]]?.toString() ?? match[0]!,
  );
}

