import 'package:flutter/material.dart';

/// Translates interface copy; source titles and chapter names fall through.
class LocalizedText extends StatelessWidget {
  const LocalizedText(
    this.data, {
    super.key,
    this.style,
    this.textAlign,
    this.maxLines,
    this.overflow,
    this.softWrap,
    this.textDirection,
    this.semanticsLabel,
    this.textScaler,
    this.textWidthBasis,
    this.textHeightBehavior,
    this.locale,
    this.strutStyle,
    this.selectionColor,
  });
  final String data;
  final TextStyle? style;
  final TextAlign? textAlign;
  final int? maxLines;
  final TextOverflow? overflow;
  final bool? softWrap;
  final TextDirection? textDirection;
  final String? semanticsLabel;
  final TextScaler? textScaler;
  final TextWidthBasis? textWidthBasis;
  final TextHeightBehavior? textHeightBehavior;
  final Locale? locale;
  final StrutStyle? strutStyle;
  final Color? selectionColor;
  @override
  Widget build(BuildContext context) => Text(
    translate(data, Localizations.localeOf(context)),
    style: style,
    textAlign: textAlign,
    maxLines: maxLines,
    overflow: overflow,
    softWrap: softWrap,
    textDirection: textDirection,
    semanticsLabel: semanticsLabel,
    textScaler: textScaler,
    textWidthBasis: textWidthBasis,
    textHeightBehavior: textHeightBehavior,
    locale: locale,
    strutStyle: strutStyle,
    selectionColor: selectionColor,
  );
}

String translate(String text, Locale locale) {
  if (locale.languageCode == 'en') return english[text] ?? text;
  if (locale.countryCode == 'TW') return traditional[text] ?? text;
  return text;
}

